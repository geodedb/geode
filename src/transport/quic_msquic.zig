pub const QuicTransport = struct {
    allocator: std.mem.Allocator,
    config: Config,
    msquic: ?*msquic.MsQuic = null,
    connections: std.ArrayList(*QuicConnection),
    cert_path: []const u8,
    key_path: []const u8,

    pub const Config = struct {
        address: []const u8 = "0.0.0.0",
        port: u16 = 7567,
        max_connections: usize = 1000,
        idle_timeout_ms: u64 = 30000,
        max_stream_data: u64 = 10 * 1024 * 1024,
        max_data: u64 = 100 * 1024 * 1024,
        cert_path: []const u8 = "certs/server.crt",
        key_path: []const u8 = "certs/server.key",
        ca_path: ?[]const u8 = null,
    };

    pub fn init(allocator: std.mem.Allocator, config: Config) !QuicTransport {
        return QuicTransport{
            .allocator = allocator,
            .config = config,
            .connections = try std.ArrayList(*QuicConnection).initCapacity(allocator, 0),
            .cert_path = config.cert_path,
            .key_path = config.key_path,
        };
    }

    pub fn deinit(self: *QuicTransport) void {
        for (self.connections.items) |conn| {
            conn.close();
            self.allocator.destroy(conn);
        }
        self.connections.deinit(self.allocator);
        
        if (self.msquic) |mq| {
            mq.deinit();
            self.msquic = null;
        }
    }

    pub fn listen(self: *QuicTransport) !void {
        // Check if certificates exist
        var cert_exists = true;
        std.fs.cwd().access(self.cert_path, .{}) catch {
            cert_exists = false;
        };
        var key_exists = true;
        std.fs.cwd().access(self.key_path, .{}) catch {
            key_exists = false;
        };

        if (!cert_exists or !key_exists) {
            if (self.generateSelfSignedCert()) |_| {
                std.debug.print("TLS_CERT_AUTOGENERATED path=\"{s}\"\n", .{self.cert_path});
            } else |err| {
                std.debug.print("{{\"level\":\"FATAL\",\"component\":\"transport\",\"msg\":\"TLS certificates not found and generation failed\",\"cert_path\":\"{s}\",\"key_path\":\"{s}\",\"error\":\"{}\"}}\n", .{ self.cert_path, self.key_path, err });
                std.debug.print("SECURITY: Refusing to start without TLS. Generate certificates manually:\n", .{});
                std.debug.print("  openssl req -x509 -newkey rsa:2048 -nodes -keyout {s} -out {s} -days 365\n", .{ self.key_path, self.cert_path });
                return QuicError.CertificateError;
            }
        }

        // Initialize msquic
        self.msquic = try msquic.MsQuic.init(self.allocator);
        errdefer if (self.msquic) |mq| mq.deinit();

        // Create server configuration with TLS
        try self.msquic.?.createServerConfiguration(
            self.cert_path,
            self.key_path,
            "geode/1",
        );

        // Start listener
        try self.msquic.?.startListener(
            self.config.address,
            self.config.port,
            "geode/1",
        );

        std.debug.print("{{\"component\":\"transport\",\"transport\":\"quic\",\"tls\":\"true\",\"port\":{d},\"library\":\"msquic\",\"status\":\"listening\"}}\n", .{self.config.port});
    }

    fn generateSelfSignedCert(self: *QuicTransport) !void {
        // Extract directory from cert_path and create it
        const cert_dir = std.fs.path.dirname(self.cert_path) orelse ".";
        std.fs.cwd().makePath(cert_dir) catch |err| switch (err) {
            error.PathAlreadyExists => {},
            else => return err,
        };

        // Generate self-signed certificate with standard OpenSSL
        const result = try std.process.Child.run(.{
            .allocator = self.allocator,
            .argv = &[_][]const u8{
                "openssl", "req", "-x509", "-newkey", "rsa:2048",
                "-keyout", self.key_path, "-out", self.cert_path, "-days",
                "365", "-nodes", "-subj", "/C=US/ST=State/L=City/O=Geode/CN=localhost",
                "-addext", "subjectAltName=DNS:localhost,DNS:geode.local,IP:127.0.0.1",
            },
        });
        defer self.allocator.free(result.stdout);
        defer self.allocator.free(result.stderr);

        if (result.term != .Exited or result.term.Exited != 0) {
            std.debug.print("OpenSSL error: {s}\n", .{result.stderr});
            return QuicError.CertificateError;
        }

        if (builtin.os.tag != .windows) {
            const cert_file = try std.fs.cwd().openFile(self.cert_path, .{});
            defer cert_file.close();
            try cert_file.chmod(0o600);

            const key_file = try std.fs.cwd().openFile(self.key_path, .{});
            defer key_file.close();
            try key_file.chmod(0o600);
        }
    }

    pub fn accept(self: *QuicTransport) !*QuicConnection {
        const mq = self.msquic.?;
        const listener_ctx = mq.listener_ctx.?;
        
        std.debug.print("[ACCEPT] Waiting for connections...\n", .{});
        
        // Poll for pending connections (already configured by listener callback)
        while (true) {
            listener_ctx.mutex.lock();
            
            if (listener_ctx.pending_connections.items.len > 0) {
                const pending = listener_ctx.pending_connections.orderedRemove(0);
                listener_ctx.mutex.unlock();
                
                std.debug.print("[ACCEPT] Got configured connection handle={*}\n", .{pending.handle});
                
                // Connection is already configured with callback and settings by listener callback
                // Just create Zig wrapper
                const conn = try self.allocator.create(QuicConnection);
                conn.* = .{
                    .allocator = self.allocator,
                    .msquic_conn = pending.handle,
                    .context = pending.context,
                    .api = mq.api,
                    .streams = std.array_list.AlignedManaged(*QuicStream, null).init(self.allocator),
                    .streams_init = true,
                };
                
                std.debug.print("[ACCEPT] Created connection wrapper\n", .{});
                
                try self.connections.append(self.allocator, conn);
                
                std.debug.print("[ACCEPT] Returning connection\n", .{});
                return conn;
            }
            
            listener_ctx.mutex.unlock();
            
            // Wait a bit for incoming connections
            std.Thread.sleep(10 * std.time.ns_per_ms);
        }
    }

    pub fn tryAccept(self: *QuicTransport) ?*QuicConnection {
        const mq = self.msquic orelse return null;
        const listener_ctx = mq.listener_ctx orelse return null;

        listener_ctx.mutex.lock();
        defer listener_ctx.mutex.unlock();

        const queue_len = listener_ctx.pending_connections.items.len;

        std.debug.print("[tryAccept] ListenerContext={*}, queue len={}, capacity={}\n", .{listener_ctx, queue_len, listener_ctx.pending_connections.capacity});

        if (queue_len > 0) {
            std.debug.print("[tryAccept] ✅ Found {} pending connection(s)\n", .{queue_len});
        }

        if (queue_len == 0) {
            return null;
        }

        const pending = listener_ctx.pending_connections.orderedRemove(0);
        std.debug.print("[tryAccept] Removed connection from queue, new count={}\n", .{listener_ctx.pending_connections.items.len});
        
        // Connection and context already configured in listener callback
        // Create Zig connection wrapper
        const conn = self.allocator.create(QuicConnection) catch {
            pending.context.deinit();
            return null;
        };
        
        conn.* = .{
            .allocator = self.allocator,
            .msquic_conn = pending.handle,
            .context = pending.context,
            .api = mq.api,
            .streams = std.array_list.AlignedManaged(*QuicStream, null).init(self.allocator),
            .streams_init = true,
        };
        
        self.connections.append(self.allocator, conn) catch {
            self.allocator.destroy(conn);
            return null;
        };
        
        return conn;
    }

    pub fn poll(self: *QuicTransport, timeout_ms: u32) !void {
        _ = self;
        _ = timeout_ms;
        // MsQuic handles polling internally via callbacks
    }
};

pub const QuicConnection = struct {
    allocator: std.mem.Allocator,
    msquic_conn: msquic.HQUIC,
    context: *msquic.ConnectionContext,
    api: *const msquic.QUIC_API_TABLE,
    streams: std.array_list.AlignedManaged(*QuicStream, null),
    streams_init: bool = false,

    pub fn close(self: *QuicConnection) void {
        if (self.streams_init) {
            for (self.streams.items) |s| {
                // Close the stream handle but context is owned by stream wrapper
                self.api.StreamClose(s.msquic_stream);
                s.context.deinit();
                self.allocator.destroy(s);
            }
            self.streams.deinit();
            self.streams_init = false;
        }
        
        self.api.ConnectionClose(self.msquic_conn);
        self.context.deinit();
    }

    pub fn isDrained(self: *QuicConnection) bool {
        _ = self;
        return false;
    }

    pub fn isHandshakeConfirmed(self: *QuicConnection) bool {
        self.context.mutex.lock();
        defer self.context.mutex.unlock();
        return self.context.connected;
    }

    pub fn acceptStream(self: *QuicConnection) !*QuicStream {
        // Non-blocking stream acceptance - returns WouldBlock if no stream is ready
        self.context.mutex.lock();
        defer self.context.mutex.unlock();

        if (self.context.pending_streams.items.len > 0) {
            const pending = self.context.pending_streams.orderedRemove(0);

            // Stream context and callback already set in PEER_STREAM_STARTED
            // Just create Zig stream wrapper
            const stream = try self.allocator.create(QuicStream);
            stream.* = .{
                .allocator = self.allocator,
                .msquic_stream = pending.handle,
                .context = pending.context,
                .api = self.api,
                .stream_id = self.streams.items.len,
            };

            try self.streams.append(stream);
            return stream;
        }

        // No stream available - return WouldBlock (non-blocking behavior)
        return error.WouldBlock;
    }

    pub fn openStream(self: *QuicConnection, bidirectional: bool) !*QuicStream {
        const flags: u32 = if (bidirectional) 0 else 1; // QUIC_STREAM_OPEN_FLAG_UNIDIRECTIONAL
        
        // Create stream context
        const stream_ctx = try msquic.StreamContext.init(self.allocator);
        errdefer stream_ctx.deinit();
        
        var stream_handle: msquic.HQUIC = null;
        const open_status = self.api.StreamOpen(
            self.msquic_conn,
            flags,
            msquic.streamCallback,
            stream_ctx,
            &stream_handle,
        );
        
        if (msquic.QUIC_FAILED(open_status)) {
            stream_ctx.deinit();
            return QuicError.StreamFailed;
        }
        
        // Start the stream
        const start_status = self.api.StreamStart(
            stream_handle,
            1, // QUIC_STREAM_START_FLAG_IMMEDIATE
        );
        
        if (msquic.QUIC_FAILED(start_status)) {
            self.api.StreamClose(stream_handle);
            stream_ctx.deinit();
            return QuicError.StreamFailed;
        }
        
        // Create Zig stream wrapper
        const stream = try self.allocator.create(QuicStream);
        stream.* = .{
            .allocator = self.allocator,
            .msquic_stream = stream_handle,
            .context = stream_ctx,
            .api = self.api,
            .stream_id = self.streams.items.len,
        };
        
        try self.streams.append(stream);
        return stream;
    }
};

pub const QuicStream = struct {
    allocator: std.mem.Allocator,
    msquic_stream: msquic.HQUIC,
    context: *msquic.StreamContext,
    api: *const msquic.QUIC_API_TABLE,
    stream_id: usize = 0,

    pub fn close(self: *QuicStream) void {
        // Just close the stream handle, don't free the context
        // The connection will clean up contexts when it closes
        self.api.StreamClose(self.msquic_stream);
    }

    pub fn write(self: *QuicStream, data: []const u8) !void {
        // Allocate a copy of the data that will live until send completes
        const data_copy = try self.allocator.dupe(u8, data);
        errdefer self.allocator.free(data_copy);
        
        // Allocate QUIC_BUFFER on heap (msquic accesses it asynchronously)
        const buffer_struct = try self.allocator.create(msquic.QUIC_BUFFER);
        errdefer self.allocator.destroy(buffer_struct);
        
        buffer_struct.* = .{
            .Length = @intCast(data_copy.len),
            .Buffer = data_copy.ptr,
        };

        // Pass the buffer pointer as context so we can identify it in SEND_COMPLETE
        const status = self.api.StreamSend(
            self.msquic_stream,
            @ptrCast(buffer_struct), // Cast single buffer pointer to array pointer
            1,
            0, // QUIC_SEND_FLAG_NONE
            data_copy.ptr, // Pass data buffer pointer as context
        );

        if (msquic.QUIC_FAILED(status)) {
            // Send failed, errdefer will clean up
            return QuicError.StreamFailed;
        }
        
        // Send successful, track buffers for cleanup on SEND_COMPLETE
        self.context.mutex.lock();
        self.context.send_buffers.append(self.context.allocator, data_copy) catch {};
        self.context.send_buffer_structs.append(self.context.allocator, buffer_struct) catch {};
        self.context.mutex.unlock();
    }

    pub fn writeAll(self: *QuicStream, data: []const u8) !void {
        try self.write(data);
    }

    pub fn read(self: *QuicStream, buf: []u8) !usize {
        self.context.mutex.lock();
        defer self.context.mutex.unlock();
        
        if (self.context.recv_buffer.items.len == 0) {
            return 0;
        }
        
        const to_copy = @min(buf.len, self.context.recv_buffer.items.len);
        @memcpy(buf[0..to_copy], self.context.recv_buffer.items[0..to_copy]);
        
        // Remove copied data
        if (to_copy < self.context.recv_buffer.items.len) {
            std.mem.copyForwards(
                u8,
                self.context.recv_buffer.items,
                self.context.recv_buffer.items[to_copy..],
            );
        }
        self.context.recv_buffer.shrinkRetainingCapacity(
            self.context.recv_buffer.items.len - to_copy
        );
        
        return to_copy;
    }

    pub fn readAll(self: *QuicStream, buf: []u8) !usize {
        return self.read(buf);
    }

    pub fn readLine(self: *QuicStream, max_size: usize) ![]u8 {
        var temp_buf = try self.allocator.alloc(u8, max_size);
        defer self.allocator.free(temp_buf);
        var pos: usize = 0;
        
        // Check if peer has shut down sending
        self.context.mutex.lock();
        const recv_complete = self.context.recv_complete;
        self.context.mutex.unlock();
        
        while (pos < max_size) {
            var byte: [1]u8 = undefined;
            const n = try self.read(&byte);
            if (n == 0) {
                // No data available
                if (recv_complete and pos == 0) {
                    // Peer shut down and no data - end of stream
                    return error.EndOfStream;
                }
                // Wait for more data if we haven't received anything yet
                if (pos == 0) {
                    std.Thread.sleep(10 * std.time.ns_per_ms);
                    continue;
                }
                break;
            }
            
            temp_buf[pos] = byte[0];
            pos += 1;
            
            if (byte[0] == '\n') break;
        }
        
        if (pos == 0) return error.WouldBlock;
        
        // Allocate exact size and copy
        const result = try self.allocator.alloc(u8, pos);
        @memcpy(result, temp_buf[0..pos]);
        return result;
    }
};

// Client-side QUIC support
pub const QuicClient = struct {
    allocator: std.mem.Allocator,
    msquic: ?*msquic.MsQuic = null,
    msquic_conn: msquic.HQUIC = null,
    conn_ctx: ?*msquic.ConnectionContext = null,
    server_addr: []const u8 = "",
    server_port: u16 = 7567,

    pub fn init(allocator: std.mem.Allocator) QuicClient {
        return QuicClient{
            .allocator = allocator,
        };
    }

    pub fn deinit(self: *QuicClient) void {
        if (self.msquic_conn != null) {
            if (self.msquic) |mq| {
                mq.api.ConnectionClose(self.msquic_conn);
            }
            self.msquic_conn = null;
        }
        if (self.conn_ctx) |ctx| {
            ctx.deinit();
            self.conn_ctx = null;
        }
        if (self.msquic) |mq| {
            mq.deinit();
            self.msquic = null;
        }
    }

    pub fn connect(self: *QuicClient, address: []const u8, port: u16) !void {
        self.msquic = try msquic.MsQuic.init(self.allocator);
        try self.msquic.?.createClientConfiguration("geode/1", false);
        self.server_addr = address;
        self.server_port = port;
        
        // Create connection context
        self.conn_ctx = try msquic.ConnectionContext.init(self.allocator, null, null);
        errdefer if (self.conn_ctx) |ctx| ctx.deinit();
        
        // Open connection
        const open_status = self.msquic.?.api.ConnectionOpen(
            self.msquic.?.registration,
            msquic.connectionCallback,
            self.conn_ctx,
            &self.msquic_conn,
        );
        
        if (msquic.QUIC_FAILED(open_status)) {
            return QuicError.ConnectionFailed;
        }
    }

    pub fn connectInsecure(self: *QuicClient, address: []const u8, port: u16, allow_insecure: bool) !void {
        std.debug.print("  connectInsecure: Starting...\n", .{});
        self.msquic = try msquic.MsQuic.init(self.allocator);
        errdefer if (self.msquic) |mq| mq.deinit();
        
        std.debug.print("  connectInsecure: Creating client config...\n", .{});
        try self.msquic.?.createClientConfiguration("geode/1", allow_insecure);
        self.server_addr = address;
        self.server_port = port;
        
        // Create connection context
        std.debug.print("  connectInsecure: Creating connection context...\n", .{});
        self.conn_ctx = try msquic.ConnectionContext.init(self.allocator, null, null);
        errdefer if (self.conn_ctx) |ctx| ctx.deinit();
        
        // Open connection
        std.debug.print("  connectInsecure: Opening connection...\n", .{});
        const open_status = self.msquic.?.api.ConnectionOpen(
            self.msquic.?.registration,
            msquic.connectionCallback,
            self.conn_ctx,
            &self.msquic_conn,
        );
        
        if (msquic.QUIC_FAILED(open_status)) {
            std.debug.print("  connectInsecure: ConnectionOpen failed: 0x{X}\n", .{open_status});
            self.msquic_conn = null;
            return QuicError.ConnectionFailed;
        }
        
        std.debug.print("  connectInsecure: Connection opened, starting...\n", .{});
        
        // For client connections, configuration is passed to ConnectionStart, not SetConfiguration
        // ConnectionSetConfiguration is only for server-side accepted connections
        
        // Start connection to server
        // Need to convert address to null-terminated string
        var addr_buf: [256]u8 = undefined;
        const addr_z = try std.fmt.bufPrintZ(&addr_buf, "{s}", .{address});
        
        std.debug.print("  connectInsecure: Calling ConnectionStart...\n", .{});
        const start_status = self.msquic.?.api.ConnectionStart(
            self.msquic_conn,
            self.msquic.?.configuration, // Pass configuration here!
            2, // AF_INET
            addr_z.ptr,
            port,
        );
        
        std.debug.print("  connectInsecure: ConnectionStart returned: 0x{X}\n", .{start_status});
        
        // ConnectionStart is async - PENDING or immediate errors are both handled via callback
        // We only fail if it's a catastrophic error (not just "no route" or "refused")
        if (start_status != msquic.QUIC_STATUS_SUCCESS and 
            start_status != msquic.QUIC_STATUS_PENDING and
            start_status != 0xFFFFFFFE) // Allow "connection refused" - will be handled by callback
        {
            std.debug.print("  connectInsecure: ConnectionStart failed with unexpected error\n", .{});
            return QuicError.ConnectionFailed;
        }
        
        std.debug.print("  connectInsecure: Connection start initiated (async)\n", .{});
    }

    pub fn connectEx(self: *QuicClient, address: []const u8, port: u16, ca: ?[]const u8, cert: ?[]const u8, key: ?[]const u8) !void {
        _ = ca;
        _ = cert;
        _ = key;
        return self.connect(address, port);
    }

    pub fn waitForHandshake(self: *QuicClient, timeout_secs: u32) !void {
        std.debug.print("    waitForHandshake: Starting (timeout={}s)...\n", .{timeout_secs});
        const ctx = self.conn_ctx orelse {
            std.debug.print("    waitForHandshake: No context!\n", .{});
            return QuicError.ConnectionFailed;
        };
        
        std.debug.print("    waitForHandshake: Got context, waiting...\n", .{});
        
        const timeout_ns = @as(u64, timeout_secs) * std.time.ns_per_s;
        const start = std.time.nanoTimestamp();
        
        while (std.time.nanoTimestamp() - start < timeout_ns) {
            std.debug.print("    waitForHandshake: ctx ptr={*}, about to lock mutex...\n", .{ctx});
            ctx.mutex.lock();
            std.debug.print("    waitForHandshake: Mutex locked\n", .{});
            const connected = ctx.connected;
            ctx.mutex.unlock();
            std.debug.print("    waitForHandshake: connected={}\n", .{connected});
            
            if (connected) {
                std.debug.print("    waitForHandshake: Connected!\n", .{});
                return;
            }
            
            std.Thread.sleep(10 * std.time.ns_per_ms);
        }
        
        std.debug.print("    waitForHandshake: Timeout\n", .{});
        return QuicError.HandshakeFailed;
    }

    pub fn getStream(self: *QuicClient) !*QuicClientStream {
        const mq = self.msquic orelse return QuicError.StreamFailed;
        
        // Create stream context
        const stream_ctx = try msquic.StreamContext.init(self.allocator);
        errdefer stream_ctx.deinit();
        
        var stream_handle: msquic.HQUIC = null;
        const open_status = mq.api.StreamOpen(
            self.msquic_conn,
            0, // Bidirectional
            msquic.streamCallback,
            stream_ctx,
            &stream_handle,
        );
        
        if (msquic.QUIC_FAILED(open_status)) {
            stream_ctx.deinit();
            return QuicError.StreamFailed;
        }
        
        // Start the stream
        const start_status = mq.api.StreamStart(
            stream_handle,
            1, // QUIC_STREAM_START_FLAG_IMMEDIATE
        );
        
        if (msquic.QUIC_FAILED(start_status)) {
            mq.api.StreamClose(stream_handle);
            stream_ctx.deinit();
            return QuicError.StreamFailed;
        }
        
        // Create client stream wrapper
        const stream = try self.allocator.create(QuicClientStream);
        stream.* = .{
            .allocator = self.allocator,
            .msquic_stream = stream_handle,
            .context = stream_ctx,
            .api = mq.api,
        };
        
        return stream;
    }
    
    // Alias for consistency with QuicConnection
    pub fn openStream(self: *QuicClient) !*QuicClientStream {
        return self.getStream();
    }
};

pub const QuicClientStream = struct {
    allocator: std.mem.Allocator,
    msquic_stream: msquic.HQUIC,
    context: *msquic.StreamContext,
    api: *const msquic.QUIC_API_TABLE,

    pub fn writeAll(self: *QuicClientStream, data: []const u8) !void {
        var buffer = msquic.QUIC_BUFFER{
            .Length = @intCast(data.len),
            .Buffer = @constCast(data.ptr),
        };

        const status = self.api.StreamSend(
            self.msquic_stream,
            @ptrCast(&buffer),
            1,
            0, // QUIC_SEND_FLAG_NONE
            null,
        );

        if (msquic.QUIC_FAILED(status)) {
            return QuicError.StreamFailed;
        }
    }

    pub fn read(self: *QuicClientStream, buf: []u8) !usize {
        self.context.mutex.lock();
        defer self.context.mutex.unlock();
        
        if (self.context.recv_buffer.items.len == 0) {
            return 0;
        }
        
        const to_copy = @min(buf.len, self.context.recv_buffer.items.len);
        @memcpy(buf[0..to_copy], self.context.recv_buffer.items[0..to_copy]);
        
        // Remove copied data
        if (to_copy < self.context.recv_buffer.items.len) {
            std.mem.copyForwards(
                u8,
                self.context.recv_buffer.items,
                self.context.recv_buffer.items[to_copy..],
            );
        }
        self.context.recv_buffer.shrinkRetainingCapacity(
            self.context.recv_buffer.items.len - to_copy
        );
        
        return to_copy;
    }

    pub fn readLine(self: *QuicClientStream, max_size: usize) ![]u8 {
        var temp_buf = try self.allocator.alloc(u8, max_size);
        defer self.allocator.free(temp_buf);
        var pos: usize = 0;
        
        // Check if peer has shut down sending
        self.context.mutex.lock();
        const recv_complete = self.context.recv_complete;
        self.context.mutex.unlock();
        
        while (pos < max_size) {
            var byte: [1]u8 = undefined;
            const n = try self.read(&byte);
            if (n == 0) {
                // No data available
                if (recv_complete and pos == 0) {
                    // Peer shut down and no data - end of stream
                    return error.EndOfStream;
                }
                // Wait for more data if we haven't received anything yet
                if (pos == 0) {
                    std.Thread.sleep(10 * std.time.ns_per_ms);
                    continue;
                }
                break;
            }
            
            temp_buf[pos] = byte[0];
            pos += 1;
            
            if (byte[0] == '\n') break;
        }
        
        if (pos == 0) return error.WouldBlock;
        
        // Allocate exact size and copy
        const result = try self.allocator.alloc(u8, pos);
        @memcpy(result, temp_buf[0..pos]);
        return result;
    }

    pub fn deinit(self: *QuicClientStream) void {
        self.api.StreamClose(self.msquic_stream);
        self.context.deinit();
        self.allocator.destroy(self);
    }
};
