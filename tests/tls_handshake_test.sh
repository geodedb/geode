#!/usr/bin/env bash
# TLS Handshake Test - Verifies QUIC+TLS handshake consistency

set -e

echo "=== QUIC TLS Handshake Verification Test ==="
echo

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m'

PASSED=0
FAILED=0

# Test function
test_handshake() {
    local test_name="$1"
    local test_cmd="$2"
    local expect_success="$3"

    echo -n "Testing $test_name... "

    # Run test with timeout
    local output
    local exit_code=0
    output=$(timeout 10 eval "$test_cmd" 2>&1) || exit_code=$?

    if [ "$expect_success" = "true" ]; then
        if [ $exit_code -eq 0 ]; then
            echo -e "${GREEN}PASS${NC}"
            ((PASSED++))
        else
            echo -e "${RED}FAIL${NC}"
            echo "  Exit code: $exit_code"
            echo "  Output: $(echo "$output" | head -3)"
            ((FAILED++))
        fi
    else
        if [ $exit_code -ne 0 ]; then
            echo -e "${GREEN}PASS${NC} (expected failure)"
            ((PASSED++))
        else
            echo -e "${RED}FAIL${NC} (expected to fail but succeeded)"
            ((FAILED++))
        fi
    fi
}

# Build first
echo "Building Geode..."
make build > /dev/null 2>&1 || { echo "Build failed"; exit 1; }

echo
echo -e "${BLUE}=== Phase 1: Server TLS Configuration ===${NC}"

# Start server in background with debug logging
echo "Starting server with TLS..."
GEODE_LOG_JSON=true ./zig-out/bin/geode serve --listen-quic 0.0.0.0:8443 > server.log 2>&1 &
SERVER_PID=$!
sleep 2

# Check if server started
if ! kill -0 $SERVER_PID 2>/dev/null; then
    echo -e "${RED}Server failed to start${NC}"
    cat server.log | grep -i error | head -5
    exit 1
fi

echo -e "${GREEN}Server started successfully${NC}"

echo
echo -e "${BLUE}=== Phase 2: Client Connection Tests ===${NC}"

# Test 1: Normal TLS connection (should fail without proper certificates)
test_handshake "TLS connection without certificates" \
    "./zig-out/bin/geode query 'RETURN 1 AS x' --server 127.0.0.1:8443" \
    false

# Test 2: Insecure connection (should work)
test_handshake "Insecure connection with --insecure flag" \
    "./zig-out/bin/geode query 'RETURN 1 AS x' --server 127.0.0.1:8443 --insecure" \
    true

# Test 3: Multiple insecure connections
test_handshake "First insecure connection" \
    "./zig-out/bin/geode query 'RETURN 2 AS y' --server 127.0.0.1:8443 --insecure" \
    true

test_handshake "Second insecure connection" \
    "./zig-out/bin/geode query 'RETURN 3 AS z' --server 127.0.0.1:8443 --insecure" \
    true

# Test 4: Concurrent insecure connections
echo
echo -e "${BLUE}=== Phase 3: Concurrent Connection Tests ===${NC}"

echo -n "Testing concurrent insecure connections... "
(
    ./zig-out/bin/geode query 'RETURN 10 AS a' --server 127.0.0.1:8443 --insecure &
    ./zig-out/bin/geode query 'RETURN 20 AS b' --server 127.0.0.1:8443 --insecure &
    ./zig-out/bin/geode query 'RETURN 30 AS c' --server 127.0.0.1:8443 --insecure &
    wait
) > concurrent.out 2>&1

if grep -q '"a":10' concurrent.out && grep -q '"b":20' concurrent.out && grep -q '"c":30' concurrent.out; then
    echo -e "${GREEN}PASS${NC}"
    ((PASSED++))
else
    echo -e "${RED}FAIL${NC}"
    echo "  Missing expected output in concurrent test"
    ((FAILED++))
fi

echo
echo -e "${BLUE}=== Phase 4: Handshake Timeout Tests ===${NC}"

# Test with debug output to verify handshake behavior
echo -n "Testing handshake completion logging... "
GEODE_LOG_LEVEL=DEBUG ./zig-out/bin/geode query 'RETURN 99 AS debug_test' --server 127.0.0.1:8443 --insecure 2>debug.log
if grep -q 'handshake completed' debug.log || grep -q 'connection initiated successfully' debug.log; then
    echo -e "${GREEN}PASS${NC}"
    ((PASSED++))
else
    echo -e "${YELLOW}WARNING${NC} - No handshake completion log found"
fi

# Clean up
echo
echo "Stopping server..."
kill $SERVER_PID 2>/dev/null || true
wait $SERVER_PID 2>/dev/null || true

echo
echo -e "${BLUE}=== Phase 5: Certificate Generation Test ===${NC}"

# Move existing certificates if they exist
if [ -d "certs" ]; then
    mv certs certs.backup.$(date +%s)
fi

# Start server again - should auto-generate certificates
echo "Starting server without certificates (should auto-generate)..."
./zig-out/bin/geode serve --listen-quic 0.0.0.0:8443 > server2.log 2>&1 &
SERVER_PID=$!
sleep 2

if grep -q 'TLS_CERT_AUTOGENERATED' server2.log; then
    echo -e "${GREEN}Certificate auto-generation successful${NC}"
    ((PASSED++))
else
    echo -e "${RED}Certificate auto-generation failed${NC}"
    ((FAILED++))
fi

# Test connection with auto-generated cert
test_handshake "Connection with auto-generated certificate" \
    "./zig-out/bin/geode query 'RETURN 100 AS auto_cert' --server 127.0.0.1:8443 --insecure" \
    true

# Clean up
kill $SERVER_PID 2>/dev/null || true
wait $SERVER_PID 2>/dev/null || true

# Restore original certificates
if [ -d "certs.backup"* ]; then
    rm -rf certs
    mv certs.backup.* certs 2>/dev/null || true
fi

echo
echo -e "${CYAN}=== Test Summary ===${NC}"
echo "Tests passed: $PASSED"
echo "Tests failed: $FAILED"
echo "Total tests: $((PASSED + FAILED))"

# Clean up temp files
rm -f server.log server2.log debug.log concurrent.out

if [ $FAILED -eq 0 ]; then
    echo -e "${GREEN}All TLS handshake tests passed!${NC}"
    exit 0
else
    echo -e "${RED}Some TLS handshake tests failed${NC}"
    echo
    echo -e "${YELLOW}Common issues:${NC}"
    echo "1. Handshake timeout with --insecure flag"
    echo "2. Certificate validation errors"
    echo "3. Connection state management issues"
    exit 1
fi
