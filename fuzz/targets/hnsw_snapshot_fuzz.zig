const std = @import("std");
const hnsw_persist = @import("hnsw_persist");
const hnsw = @import("hnsw");
const FuzzCtx = struct {};

fn capped(data: []const u8) []const u8 {
    return data[0..@min(data.len, 1_000_000)];
}

// Zig 0.16: std.testing.fuzz hands the test a *Smith generator instead of a
// raw byte slice.  Draw a fuzzer-controlled byte slice from the Smith and
// feed it to the original byte-driven harness.
fn fuzz_hnsw_snapshot(context: FuzzCtx, smith: *std.testing.Smith) anyerror!void {
    const ally = std.testing.allocator;
    const buf = try ally.alloc(u8, 64 * 1024);
    defer ally.free(buf);
    const len = smith.slice(buf);
    try fuzz_hnsw_snapshot_bytes(context, buf[0..len]);
}

fn fuzz_hnsw_snapshot_bytes(context: FuzzCtx, data: []const u8) anyerror!void {
    _ = context;
    const slice = capped(data);
    const ally = std.testing.allocator;
    // Zig 0.16: std.fs.cwd() removed; use std.Io.Dir with an explicit Io.
    const io = std.Io.Threaded.global_single_threaded.io();
    try std.Io.Dir.cwd().createDirPath(io, "zig-cache/fuzz/hnsw");
    var snap_name_buf: [96]u8 = undefined;
    var vec_name_buf: [96]u8 = undefined;
    const snap_name = try std.fmt.bufPrint(&snap_name_buf, "zig-cache/fuzz/hnsw/snap-{d}.bin", .{@intFromPtr(slice.ptr)});
    const vec_name = try std.fmt.bufPrint(&vec_name_buf, "zig-cache/fuzz/hnsw/vec-{d}.bin", .{@intFromPtr(slice.ptr) ^ 0x9e37});
    {
        var f = try std.Io.Dir.cwd().createFile(io, snap_name, .{});
        defer f.close(io);
        try f.writeStreamingAll(io, slice);
    }
    {
        var f = try std.Io.Dir.cwd().createFile(io, vec_name, .{});
        defer f.close(io);
        try f.writeStreamingAll(io, slice);
    }

    // Any load failure on fuzzer-generated bytes is acceptable; the harness
    // only asserts that loading never crashes and round-trips when it succeeds.
    var loaded = hnsw_persist.loadSnapshot(ally, snap_name, vec_name) catch return;
    defer loaded.deinit();

    const out_snap = try std.fs.path.join(ally, &.{ "zig-cache/fuzz/hnsw", "out-snap.bin" });
    defer ally.free(out_snap);
    const out_vec = try std.fs.path.join(ally, &.{ "zig-cache/fuzz/hnsw", "out-vec.bin" });
    defer ally.free(out_vec);
    try hnsw_persist.saveSnapshot(&loaded, out_snap, out_vec);
}

test "fuzz hnsw snapshot" {
    try std.testing.fuzz(FuzzCtx{}, fuzz_hnsw_snapshot, .{});
    std.debug.print("fuzzing: completed\n", .{});
}
